import math
numero1 = int(input("Digite o primeiro valor inteiro: "))
numero2 = int(input("Digite o segundo valor inteiro: "))
cubo = numero2 **3
mediageo = (numero1) * (numero2)
mediageo = math.sqrt (mediageo) 
print (f"O cubo do segundo número é: {cubo}.")
print (f"A média geométrica é: {mediageo}.")
